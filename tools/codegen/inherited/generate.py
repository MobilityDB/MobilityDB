def _accessor_names() -> set:
    """Every SQL function name the generated accessor region can carry: the shared
    template's functions plus the gated TNumber/orderable reductions. Used to find and
    remove the pre-existing hand-written definitions when bootstrapping a new family.
    # BINDING-HEADER-PARSE-OK: reads the SQL accessors.sql.tmpl template (not a C
    # header), exactly as render_accessors/_accessor_blocks already do; this is the
    # inherited SQL-region generator, not a catalog-consuming binding."""
    tmpl = (TEMPLATES / "accessors.sql.tmpl").read_text()
    return set(re.findall(r"CREATE FUNCTION (\w+)\(", tmpl)) | set(_GATED)


def bootstrap_accessors(filetext: str, fam: dict, rendered: str) -> str:
    """Create the GENERATED-ACCESSORS region for a family that does not have one yet,
    so adding an accessor family is fully declarative (a manifest entry) with NO
    hand-placed marker. The region is inserted where the family's FIRST canonical
    accessor is currently hand-written, and every hand-written definition of a canonical
    accessor (for the family's temporal type(s), wherever it sits in the file — e.g. a
    `valueAtTimestamp` parked in a restriction section) is removed so the region is the
    single source. Idempotent on the next run: the markers now exist, so the normal
    splice/validate path takes over."""
    temps = [t["temp"] for t in (fam.get("types") or [{"temp": fam["temp"]}])]
    names = _accessor_names()

    def block_re(name: str, temp: str):
        return re.compile(rf"^CREATE FUNCTION {re.escape(name)}\({re.escape(temp)}\b"
                          rf"[^;]*?LANGUAGE[^;]*;\n", re.S | re.M)

    first = None
    for name in names:
        for temp in temps:
            m = block_re(name, temp).search(filetext)
            if m and (first is None or m.start() < first):
                first = m.start()
    if first is None:
        raise SystemExit(f"bootstrap accessors {fam['family']}: no canonical accessor "
                         f"of {temps} found in {fam['file']}")
    prefix, rest = filetext[:first], filetext[first:]
    for name in names:
        for temp in temps:
            rest = block_re(name, temp).sub("", rest)
    rest = re.sub(r"\A\n+", "", rest)  # the region supplies its own leading blank line
    begin, end = _accessors_markers(fam["family"])
    text = prefix + begin + rendered + end + "\n" + rest
    return re.sub(r"\n\n\n+", "\n\n", text)  # tidy the blank runs left by the removals


def bootstrap_representations(filetext: str, fam: dict, rendered: str) -> str:
    """Create the GENERATED-REPRESENTATIONS region for a family whose representation
    block is still a bare hand-written section (no markers). Unlike accessors the block
    is CONTIGUOUS — the same section-header anchors extract_representations slices by —
    so wrap exactly that span with the markers; the enclosed text is the rendered block,
    byte-identical to the committed hand block (--validate proves it before the flip).
    Idempotent afterward: the markers exist, so the splice path reproduces this output."""
    i = filetext.index(fam["begin"])
    start = filetext.rfind("/*", 0, i)
    begin, end = _representations_markers(fam["family"])
    if fam.get("whole_file"):
        return filetext[:start] + begin + rendered + end
    j = filetext.index(fam["end"])
    block_end = filetext.rfind("/*", 0, j)
    return filetext[:start] + begin + rendered + end + "\n" + filetext[block_end:]


# --- B-tree comparison sub-family (SQL, per-family region-in-file) ---------------
# The Temporal<T> comparison-and-B-tree-indexing surface every temporal type carries:
# the six comparison functions lt/le/eq/ne/ge/gt plus cmp (backing the generic
# Temporal_lt/_le/_eq/_ne/_ge/_gt/_cmp kernels), the six B-tree operators
# `< <= = <> >= >` with their COMMUTATOR/NEGATOR clauses, and the
# `CREATE OPERATOR CLASS <temp>_btree_ops ... USING btree` opclass. The CREATE
# FUNCTION set is uniform across families (only the temporal type token varies, the
# backing symbol and RETURNS are fixed lt/le/eq/ne/ge/gt->bool + cmp->int4) so ONE
# four-line skeleton (templates/comparisons.sql.tmpl) emits every function; the
# operators, opclass, section banner and per-type dividers carry per-family
# whitespace/selectivity irregularities (spatial families use tspatial_sel/joinsel,
# the scalar families use scalar per-op selectivity, and the opclass spacing drifts)
# so they are reproduced BYTE-EXACT via `lit` blocks in the manifest, exactly as the
# constructor surface reproduces its section headers and family-extra overloads.
#
# `--validate` extracts the committed hand block by section-header ANCHORS
# (marker-aware, mirroring extract_constructors: sliced by GENERATED-COMPARISONS
# markers once they exist, else by the banner header down to the divider that opens
# the B-tree/hash tail), so the deployed .in.sql files are untouched while the
# template is proven. The pointcloud families (tpcpoint/tpcpatch) are intentionally
# absent from the manifest: their B-tree block interleaves with the hash block with
# no separating divider and reorders the functions (eq/ne/lt/le/ge/gt) with a
# distinct RETURNS spelling and one-line operator layout, so it is not a token-swap
# of the shared skeleton; likewise the base temporal families (span/spanset/tbox/
# temporal) group functions across multiple base types with non-contiguous
# operators/opclasses and Span_*/Tbox_* symbols. Both are classified out by omission
# from the data, never by a code-level skip.
#
# The value-domain Set<T> families ARE in the manifest (`ops: set` selects the
# Set_* kernel table). Their skeleton-rendered `funcs` cover the canonical 4-line
# spelling; a multi-type file (001_set: six alpha base types, 050_geoset:
# geomset+geogset) lists its types op-outer via a `funcs` token LIST. Two shapes are
# reproduced via `lit` instead of the skeleton, encoded, never normalized:
# h3indexset/quadbinset spell the functions in a compact 3-line form (`RETURNS
# boolean AS 'MODULE_PATHNAME', ...`) with `hash()` interleaved between `cmp()`
# and the operators — the region is contiguous, so that interior function stays
# inside it as part of the compact-form `lit` — and the pointcloud sets
# (pcpointset/pcpatchset) have no `/*` divider between the B-tree opclass and the
# hash tail. Both shapes therefore close their region with `end_exact: true`: the
# slice ends exactly at the `end:` anchor (the hash opclass for h3indexset/
# quadbinset, the first hash function for the pointcloud sets) instead of at the
# `/*` opening the section the anchor names, which keeps the hash tail OUT of the
# comparison region so the hash surface can be owned separately.
def _comparisons_markers(family: str):
    begin = (f"-- GENERATED-COMPARISONS-BEGIN {family} — "
             "tools/codegen/inherited/generate.py from templates/comparisons.sql.tmpl;\n"
             "-- DO NOT EDIT BY HAND; edit the template + manifest.d/comparison_families.yaml "
             "and re-run.\n")
    return begin, f"-- GENERATED-COMPARISONS-END {family}\n"


# Default op -> (RETURNS, backing C symbol) for the six comparison functions plus the
# B-tree support `cmp`; the fully canonical generic comparison set, identical for
# every temporal family. A value-domain Set<T> family selects the _SET_CMP_OPS table
# instead via `ops: set`; a family that deviates otherwise would override via a
# `funcs` spec, none do today.
_CMP_OPS = [
    ("lt", "boolean", "Temporal_lt"),
    ("le", "boolean", "Temporal_le"),
    ("eq", "boolean", "Temporal_eq"),
    ("ne", "boolean", "Temporal_ne"),
    ("ge", "boolean", "Temporal_ge"),
    ("gt", "boolean", "Temporal_gt"),
    ("cmp", "integer", "Temporal_cmp"),
]
# The base temporal file (022_temporal) spells the same seven functions with
# RETURNS `boolean` and cmp -> `integer` (the derived families spell `bool`/`int4`),
# reproduced verbatim, never normalized; selected via `ops: base`.
_BASE_CMP_OPS = [
    ("lt", "boolean", "Temporal_lt"),
    ("le", "boolean", "Temporal_le"),
    ("eq", "boolean", "Temporal_eq"),
    ("ne", "boolean", "Temporal_ne"),
    ("ge", "boolean", "Temporal_ge"),
    ("gt", "boolean", "Temporal_gt"),
    ("cmp", "integer", "Temporal_cmp"),
]
# The Set<T> comparison surface is the same seven-function skeleton backed by the
# Set_* kernels, in the canonical set-file order (eq/ne before the inequalities,
# unlike the temporal lt-first order) and with cmp spelled `integer` (the temporal
# files spell it `int4`) — both reproduced verbatim, never normalized.
_SET_CMP_OPS = [
    ("eq", "boolean", "Set_eq"),
    ("ne", "boolean", "Set_ne"),
    ("lt", "boolean", "Set_lt"),
    ("le", "boolean", "Set_le"),
    ("ge", "boolean", "Set_ge"),
    ("gt", "boolean", "Set_gt"),
    ("cmp", "integer", "Set_cmp"),
]


def _cmp_funcs(types, ops=_CMP_OPS) -> str:
    """Render the seven comparison CREATE FUNCTIONs from the shared skeleton
    (templates/comparisons.sql.tmpl). `types` is one type token (the temporal shape:
    the seven functions packed with no blank line between them) or a list of tokens
    (the multi-type set files 001_set/050_geoset: grouped op-outer / type-inner —
    every type's eq, then every type's ne, ... — the op groups separated by one
    blank line, no blank within a group). The block ends with the trailing newline
    of the last function; the blank line that separates it from the following
    operators is part of the surrounding `lit` block."""
    tmpl = (TEMPLATES / "comparisons.sql.tmpl").read_text().rstrip("\n")
    if isinstance(types, str):
        types = [types]
    groups = ["\n".join(tmpl.replace("{SIG}", f"{name}({t}, {t})")
                            .replace("{RET}", ret).replace("{SYM}", sym)
                        for t in types)
              for name, ret, sym in ops]
    return ("\n\n" if len(types) > 1 else "\n").join(groups) + "\n"


def render_comparisons(fam: dict) -> str:
    """Render one family's comparison block from its `blocks` sequence. A block is a
    verbatim `lit` (the section banner, operators, B-tree opclass and per-type
    dividers, kept exactly as the hand file) or a `funcs` type token / token list (the
    seven comparison functions rendered from the shared skeleton, backed by the
    Temporal_* kernels, or by the Set_* kernels when the family carries `ops: set`).
    Blocks concatenate with no automatic separator — every separator is baked into the
    `lit` blocks — so the rendered text is byte-identical to the committed region."""
    ops = {"set": _SET_CMP_OPS, "base": _BASE_CMP_OPS}.get(fam.get("ops"), _CMP_OPS)
    out = ""
    for blk in fam["blocks"]:
        out += blk["lit"] if "lit" in blk else _cmp_funcs(blk["funcs"], ops)
    return out


