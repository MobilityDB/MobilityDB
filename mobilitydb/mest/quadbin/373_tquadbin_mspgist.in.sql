  OPERATOR  4    &> (tquadbin, tquadbin),
  -- strictly right
  OPERATOR  5    >> (tquadbin, stbox),
  OPERATOR  5    >> (tquadbin, tquadbin),
  -- contained by
  OPERATOR  8    <@ (tquadbin, tstzspan),
  OPERATOR  8    <@ (tquadbin, stbox),
  OPERATOR  8    <@ (tquadbin, tquadbin),
  -- overlaps or below
